/**
 * Builds the Vercel serverless entrypoints.
 *
 * Vercel discovers files in /api before the project's build command runs, so
 * the entrypoint files themselves must already exist in the repository. The
 * TypeScript sources live in /serverless and are bundled into self-contained
 * ESM files in /api by this script. That removes the runtime cross-directory
 * import that caused:
 *
 *   ERR_MODULE_NOT_FOUND: Cannot find module
 *   '/var/task/src/server/superAdminHandler' imported from
 *   '/var/task/api/super-admin.js'
 *
 * Run automatically by `npm run build`. Re-run after changing server code.
 */
import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const outdir = path.join(root, 'api');

await mkdir(outdir, { recursive: true });

const entries = [
  { in: path.join(root, 'serverless/super-admin.ts'), out: 'super-admin' },
  { in: path.join(root, 'serverless/head-auth.ts'), out: 'head-auth' },
];

await build({
  entryPoints: entries.map(({ in: entry, out }) => ({ in: entry, out })),
  outdir,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // Dependencies are installed by Vercel and traced normally. Bundling local
  // source is what fixes the cross-directory ESM resolution failure.
  packages: 'external',
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  logLevel: 'info',
  banner: {
    js: '// AUTO-GENERATED by scripts/build-api.mjs — edit serverless/*.ts or src/server/*.ts instead.',
  },
});

console.log('[build-api] Bundled api/super-admin.js and api/head-auth.js');
